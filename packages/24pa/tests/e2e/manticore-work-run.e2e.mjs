import { afterAll, beforeAll, expect, it } from 'vitest';
import { mkdir, mkdtemp, rm, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { bootHost } from '../helpers/host.mjs';
import { startMockLlm } from '../helpers/mock-llm.mjs';
import { startPgCluster } from '../helpers/pg.mjs';
import { DEFAULT_CONFIG } from '../../lib/config.js';
let root, host, llm, cluster, binding, env, scriptPath, previousExtras, effectPath;
const script = async (title, waiting = false) => writeFile(scriptPath, JSON.stringify({ mode: 'dispatch', delegate: { worker: 'memo', title, instruction: '只处理这项原目标', completionCriteria: '结果包含可核对出处', acceptanceRequired: true },
  workerTool: { name: 'pa24_run', input: waiting ? { action: 'wait', reason: '需要主人确认主题', kind: 'input' } : { action: 'progress', stage: '已核对输入', completed: '完成原资料核对', next: '交付结果和出处' } }, workerReply: 'WORK_RESULT：完成本次目标，出处为原请求；未完成项：无。' }));
beforeAll(async () => {
  root = await mkdtemp(join(tmpdir(), 'pa24-work-run-')); const workspace = join(root, 'workspace'); await mkdir(workspace);
  const fixture = join(root, 'lost-receipt-plugin'); await mkdir(fixture);
  await writeFile(join(fixture, 'package.json'), JSON.stringify({ name: 'pa24-test-worker-lost-receipt', version: '0.0.0', type: 'module', exports: { '.': './index.mjs' }, dsh: { bundle: { patch: './cordis.patch.yml' } } }));
  await writeFile(join(fixture, 'cordis.patch.yml'), '- insert:\n    - id: pa24-test-worker-lost-receipt\n      name: pa24-test-worker-lost-receipt\n');
  await writeFile(join(fixture, 'index.mjs'), await readFile(new URL('../helpers/work-run-lost-receipt.mjs', import.meta.url)));
  previousExtras = process.env.PA24_E2E_EXTRA_PLUGINS;
  process.env.PA24_E2E_EXTRA_PLUGINS = [previousExtras, fixture].filter(Boolean).join(',');
  effectPath = join(root, 'tool-effects.jsonl'); await writeFile(effectPath, '');
  const storage = process.env.PA24_E2E_STORAGE === 'postgres' ? 'postgres' : 'sqlite';
  if (storage === 'postgres') cluster = await startPgCluster();
  await writeFile(join(workspace, 'AGENTS.md'), '# 隔离交办验证\n\n```json\n' + JSON.stringify({ ...DEFAULT_CONFIG, storage, maxWorkers: 2 }) + '\n```\n');
  scriptPath = join(root, 'script.json'); await writeFile(scriptPath, '{}');
  llm = await startMockLlm({ scriptPath, logPath: join(root, 'requests.json'), recordInputs: true });
  env = { PA24_WORKSPACE: workspace, PA24_TRANSPORT: 'fake', PA24_TEST_WORK_EFFECT: effectPath, DEEPSEEK_API_KEY: 'test-key', DEEPSEEK_BASE_URL: llm.url, ...(cluster ? { PA24_PG_DSN: cluster.dsn } : {}) };
  host = await bootHost({ env }); binding = (await host.waitUntil(v => !!v.workspace?.localSessionId && !!v.workspaceBinding)).workspaceBinding;
}, 600000);
afterAll(async () => { await host?.stop(); await llm?.close(); await cluster?.stop(); if (root) await rm(root, { recursive: true, force: true });
  if (previousExtras === undefined) delete process.env.PA24_E2E_EXTRA_PLUGINS; else process.env.PA24_E2E_EXTRA_PLUGINS = previousExtras; });
const until = async (read, check) => { const end = Date.now() + 30000; while (Date.now() < end) { const value = await read(); if (check(value)) return value; await new Promise(r => setTimeout(r, 80)); } throw Error('交办验收等待超时：' + JSON.stringify(await read()) + '\n' + JSON.stringify(host.logs()).slice(-5000)); };
const inspect = id => host.api('work.inspect', { workId: id, workspaceBinding: binding });
const detail = id => host.api('worker.run', { runId: id, workspaceBinding: binding });
const command = (work, op, instruction, extra = {}) => ({ type: 'work.change', workspaceBinding: binding, workId: work.id, expectedRevision: work.revision, requestId: randomUUID(), op, instruction, confirm: true, ...extra });
const create = async (title, waiting = false) => {
  await script(title, waiting); const sessionId = (await host.api('snapshot')).workspace.localSessionId;
  await host.remote('session/prompt', { request: { requestId: randomUUID(), sessionId, mode: 'queue', content: [{ type: 'text', text: title }], clientTimeZone: 'Asia/Shanghai' } });
  const state = await host.waitUntil(v => v.work.some(w => w.title === title && w.status === (waiting ? 'waiting_input' : 'completed')), { timeoutMs: 30000, label: title });
  return (await inspect(state.work.find(w => w.title === title).id)).work;
};
it('真实交办有阶段、原请求、完成依据与固定投递；验收重复请求只写一次', async () => {
  const work = await create('交付与主人验收'); const run = await detail(work.active_worker_run_id);
  expect(run.run.result).toContain('WORK_RESULT'); expect(run.run.snapshot.execution.persona).toBeTruthy();
  expect(run.run.progress_detail).toMatchObject({ completed: '完成原资料核对', next: '交付结果和出处' });
  expect(run.inputs[0].status).toBe('adopted'); expect(work.acceptance_status).toBe('pending');
  expect(run.deliveries).toHaveLength(1); expect(run.deliveries[0].target).toBe(work.parent_session_id);
  const input = command(work, 'return', '还需补充附件'); await host.api('action', input);
  const returned = (await inspect(work.id)).work; expect(returned.acceptance_status).toBe('returned'); expect(returned.status).toBe('completed');
  const accept = command(returned, 'accept', '已人工核对附件与出处');
  const [one, two] = await Promise.all([host.api('action', accept), host.api('action', accept)]);
  expect(one.work.acceptance_status).toBe('accepted'); expect(two.work.revision).toBe(one.work.revision);
  expect((await inspect(work.id)).changes.filter(row => row.record.op === 'accept')).toHaveLength(1);
  await expect(host.api('action', command(work, 'accept', '旧页面确认'))).rejects.toThrow('新进展');
}, 60000);
it('等待期间重启后补充沿原交办原运行采用，累计执行时限与历史保留', async () => {
  let work = await create('等待补充后恢复', true), first = work.active_worker_run_id;
  await until(() => detail(first), v => v.calls.every(c => c.status !== 'running'));
  const before = (await detail(first)).execution;
  const hostRoot = host.root; await host.stop({ keepRoot: true }); host = await bootHost({ env, root: hostRoot });
  binding = (await host.waitUntil(v => !!v.workspaceBinding && !!v.workspace?.localSessionId)).workspaceBinding;
  work = (await inspect(work.id)).work; expect(work.status).toBe('waiting_input');
  await script('等待补充后恢复'); await host.api('action', command(work, 'supplement', '主题确认：本周复盘'));
  const result = await until(() => inspect(work.id), v => v.work.status === 'completed');
  expect(result.work.active_worker_run_id).toBe(first); expect(result.runs.total).toBe(1);
  const run = await detail(first); expect(run.inputs).toHaveLength(2); expect(run.inputs.every(input => input.status === 'adopted')).toBe(true);
  expect(run.execution.executionMs).toBeGreaterThanOrEqual(before.executionMs); expect(run.execution.blocks).toHaveLength(0);
  expect(run.run.result).toContain('WORK_RESULT');
}, 600000);
it('等待停止得到宿主确认；迟到补充不能复活，明确接续新增关联运行', async () => {
  let work = await create('停止与接续', true), first = work.active_worker_run_id;
  await until(() => detail(first), v => v.calls.every(c => c.status !== 'running'));
  await host.api('action', command(work, 'stop', ''));
  const stopped = await until(() => detail(first), v => v.run.status === 'stopped'); expect(stopped.execution.stop.settledAt).toBeTruthy();
  work = (await inspect(work.id)).work;
  await expect(host.api('action', command(work, 'supplement', '迟到的信息'))).rejects.toThrow('补充不会复活');
  await script('停止与接续'); work = (await inspect(work.id)).work;
  await host.api('action', command(work, 'continue', '只完成尚未执行的报告，不重做已保存动作'));
  const result = await until(() => inspect(work.id), v => v.work.status === 'completed');
  expect(result.runs.total).toBe(2); expect(result.work.active_worker_run_id).not.toBe(first);
  expect((await detail(result.work.active_worker_run_id)).run.snapshot.fromRunId).toBe(first);
  expect((await detail(first)).run.status).toBe('stopped');
}, 60000);
it('新目标建立独立关联交办，只带显式选择的上下文', async () => {
  const work = await create('已有成果');
  const result = await host.api('action', command(work, 'new-goal', '只携带我选定的结论A', { title: '基于成果的新目标' }));
  const child = await until(() => inspect(result.workId), v => v.work.status === 'completed');
  expect(child.work.parent_work_item_id).toBe(work.id); expect(child.work.instruction).toBe('只携带我选定的结论A');
  expect((await inspect(work.id)).runs.total).toBe(1); expect(child.runs.total).toBe(1);
}, 60000);
it('真实工具写入后回执丢失阻断后续模型，重启和迟到补充不重做，核对后接续新运行', async () => {
  const title = '真实工具未知回执'; await script(title);
  const configured = JSON.parse(await readFile(scriptPath, 'utf8'));
  configured.workerTool.input.stage = 'TEST_LOST_ACKNOWLEDGEMENT'; await writeFile(scriptPath, JSON.stringify(configured));
  const sessionId = (await host.api('snapshot')).workspace.localSessionId;
  await host.remote('session/prompt', { request: { requestId: randomUUID(), sessionId, mode: 'queue', content: [{ type: 'text', text: title }] } });
  const snapshot = await host.waitUntil(v => v.work.some(w => w.title === title && w.status === 'needs_reconciliation'));
  let work = (await inspect(snapshot.work.find(w => w.title === title).id)).work; const first = work.active_worker_run_id;
  const uncertain = await until(() => detail(first), v => v.calls.some(call => call.status === 'unknown'));
  expect(uncertain.calls).toHaveLength(1); expect(uncertain.calls[0].result.isError).toBe(true);
  const requests = () => llm.requests.filter(request => (request.inputs ?? []).some(message => (message.content ?? []).some(part => part.text === `[24PA execution: ${work.execution_id}]`)));
  expect(requests()).toHaveLength(1); expect((await readFile(effectPath, 'utf8')).trim().split('\n')).toEqual([work.id]);
  const hostRoot = host.root; await host.stop({ keepRoot: true }); host = await bootHost({ env, root: hostRoot });
  binding = (await host.waitUntil(v => !!v.workspaceBinding && !!v.workspace?.localSessionId)).workspaceBinding;
  work = (await inspect(work.id)).work; expect(work.status).toBe('needs_reconciliation');
  await expect(host.api('action', command(work, 'supplement', '再试一次'))).rejects.toThrow('核对');
  await host.api('action', command(work, 'stop', ''));
  await until(() => detail(first), v => v.run.status === 'stopped'); work = (await inspect(work.id)).work;
  await expect(host.api('action', command(work, 'continue', '换个参数继续'))).rejects.toThrow('未核对动作');
  const evidence = await detail(first); work = (await inspect(work.id)).work;
  await host.api('action', command(work, 'review', '', { runId: first, fingerprint: evidence.fingerprint, summary: '隔离文件中已有原写入', completed: '原工具副作用已完成一次', remaining: '仅报告结果',
    calls: [{ id: evidence.calls[0].id, outcome: 'completed', evidence: '独立效果日志保留一次原 Worker 标识' }] }));
  await script(title); work = (await inspect(work.id)).work;
  await host.api('action', command(work, 'continue', '只报告已完成写入，不重做原动作'));
  const completed = await until(() => inspect(work.id), v => v.work.status === 'completed');
  expect(completed.work.active_worker_run_id).not.toBe(first); expect(completed.runs.total).toBe(2);
  expect((await detail(first)).run.status).toBe('stopped'); expect((await detail(first)).calls[0].status).toBe('unknown');
  expect((await readFile(effectPath, 'utf8')).trim().split('\n')).toEqual([work.id]);
}, 600000);
