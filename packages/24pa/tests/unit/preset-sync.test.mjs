import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';
import { generatePa24Patch, resolveBaseline } from '../../scripts/sync-preset.mjs';

const pkgDir = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const JS_EXPR_TAG = { tag: 'tag:yaml.org,2002:js', resolve: (value) => value };

describe('预设同步生成器', () => {
  const { standardPath, version } = resolveBaseline();
  const generated = generatePa24Patch(readFileSync(standardPath, 'utf8'), version);

  it('生成结果与已提交 cordis.patch.yml 逐字节一致（防漂移守护）', () => {
    const checked = readFileSync(resolve(pkgDir, 'cordis.patch.yml'), 'utf8');
    expect(generated).toBe(checked);
  });

  it('头注释标注生成来源与基线版本', () => {
    expect(generated.startsWith('# GENERATED by packages/24pa/scripts/sync-preset.mjs')).toBe(true);
    // #115 起头注释为「(baseline X; verified …)」续行格式，锚定分号钉住该格式
    expect(generated.split('\n').slice(0, 5).join('\n')).toContain(`(baseline ${version};`);
  });

  it('delta 语义：身份重写、排除项与新增行各就各位', () => {
    const doc = parse(generated, { customTags: [JS_EXPR_TAG] });
    expect(doc).toHaveLength(1);
    const insert = doc[0].insert;

    const preset = insert.find((row) => row.id === 'pa24-preset');
    expect(preset.name).toBe('@deepseek-ai/dsh-agent-preset');
    expect(preset.config.id).toBe('pa24');
    expect(preset.config.name).toBe('24私助');
    expect(preset.config.description).toContain('私人助理');
    expect(preset.config.order).toBeUndefined();

    const plugins = preset.config.plugins;
    const ids = plugins.map((row) => row.id);
    expect(plugins.find((row) => row.id === 'persona').config.prefix).toContain('24私助（24PA）');

    // 提醒保持账本单轨：schedule 工具及其痕迹全部排除。
    expect(ids).not.toContain('tool-schedule');
    expect(ids).not.toContain('tool-plugin-manager');
    expect(JSON.stringify(plugins)).not.toContain('schedule_create');
    expect(JSON.stringify(plugins)).not.toContain('modelSelectionSettings');

    const delegationIds = plugins.find((row) => row.id === 'delegation').config.map((row) => row.id);
    expect(delegationIds.indexOf('tool-subagent-codex')).toBe(delegationIds.indexOf('tool-subagent-fork') + 1);
    expect(delegationIds.indexOf('tool-subagent-claude-code')).toBe(delegationIds.indexOf('tool-subagent-codex') + 1);
    expect(delegationIds.indexOf('tool-ralph')).toBe(delegationIds.indexOf('tool-workflow') + 1);

    expect(ids[ids.length - 1]).toBe('pa24-agent');

    // 宿主插件行必须在同一 insert 列表内：顶层裸条目是按 id 的覆盖，没有目标行会被跳过。
    const host = insert.find((row) => row.id === 'pa24');
    expect(host.name).toBe('@benz-ai-x/dsh-24pa');
    expect(host.config.stateDirectory).toBe("dshHomePath('24pa')");
    expect(host.config.workspacePath).toBe("process.env.PA24_WORKSPACE || ''");
    expect(host.config.larkCliBin).toBe('lark-cli');
    expect(host.config.wecomCliBin).toBe('wecom-cli');
  });

  it('基线锚点缺失时显式失败，而非静默产出残缺预设', () => {
    const broken = JSON.stringify([
      { insert: [{ id: 'preset-standard', name: '@deepseek-ai/dsh-agent-preset', config: { id: 'standard', plugins: [] } }] },
    ]);
    expect(() => generatePa24Patch(broken, 'test')).toThrow(/anchor missing/);
  });
});

describe('宿主版本三串一致性（#114/#118 守卫）', () => {
  it('engines.dsh 与 peer dsh / dsh-schedule 逐字相同——engines 是装载校验实际读点', () => {
    const pkg = JSON.parse(readFileSync(resolve(pkgDir, 'package.json'), 'utf8'));
    const engines = pkg.engines.dsh;
    expect(pkg.peerDependencies['@deepseek-ai/dsh']).toBe(engines);
    expect(pkg.peerDependencies['@deepseek-ai/dsh-schedule']).toBe(engines);
    // 兼容清单只增不减地覆盖已发布宿主基线；出现新基线时三处必须同扩。
    // alpha.3–5 不单列：preset 生成物与 alpha.2 逐字一致（PR #114/#118 核验），三串由 engines 整体覆盖
    for (const baseline of ['0.2.0-rc.2', '0.2.1-alpha.1', '0.2.1-alpha.2', '0.2.1-rc.1', '0.2.1-rc.2', '0.2.1-rc.3', '0.2.1-rc.4']) {
      expect(engines).toContain(baseline);
    }
  });
});
