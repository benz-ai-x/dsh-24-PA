// Generate cordis.patch.yml from the dsh baseline's standard agent preset.
//
// The pa24 preset is "standard + delta" by the C-1..C-8 decision (spec 1.3),
// but the loader's patch layer cannot express inheritance: id-targeted
// patches replace `config` wholesale (vendor/include applyEntryPatches) and
// `insert` only appends into loader-level groups, never into an agent-preset
// row's `config.plugins`. The preset therefore ships as a copy — this script
// keeps that copy generated instead of hand-maintained:
//
//   npm run preset:sync     regenerate cordis.patch.yml and overwrite it
//   npm run preset:check    fail when the checked-in file drifted (CI guard)
//
// The baseline is the devDependency `@deepseek-ai/dsh-web-app` (exact pin);
// its published tarball ships presets/standard.patch.yml. Bump that pin on a
// new dsh baseline, rerun sync, and review the generated diff — anchor
// failures below mean upstream moved something the delta assumed, so a human
// must re-derive the affected rule before regenerating.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Scalar, YAMLMap, parseDocument } from 'yaml';

const require = createRequire(import.meta.url);
const pkgDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// `!!js` scalars survive the round trip as raw expression strings, exactly the
// dialect dsh's own patch tooling uses (customTags resolve-to-string).
const JS_EXPR_TAG = { tag: 'tag:yaml.org,2002:js', resolve: (value) => value };

const PRESET = {
  rowId: 'pa24-preset',
  configId: 'pa24',
  name: '24私助',
  description: '统一承接日常事务交办与工作区维护的私人助理，具备标准模式的完整编程能力。',
  personaPrefix: '你是24私助（24PA），由 {{model}} 模型驱动的私人助理，同时具备完整的编程 Agent 能力。',
};

const SCHEDULE_TOOLS = ['schedule_create', 'schedule_delete', 'schedule_list', 'schedule_update'];

const EXTERNAL_SUBAGENTS = [
  {
    id: 'tool-subagent-codex',
    name: '@deepseek-ai/dsh-tool-subagent',
    config: { provider: 'codex', toolName: 'subagent_codex', backgroundMode: 'one-shot', maxDepth: 'provider-managed' },
  },
  {
    id: 'tool-subagent-claude-code',
    name: '@deepseek-ai/dsh-tool-subagent',
    config: { provider: 'claude-code', toolName: 'subagent_claude_code', backgroundMode: 'one-shot', maxDepth: 'provider-managed' },
  },
];

const RALPH_ROW = {
  id: 'tool-ralph',
  name: '@deepseek-ai/dsh-tool-ralph',
  config: { subagentProvider: 'spawn', maxRounds: 64 },
};

const PA24_AGENT_ROW = { id: 'pa24-agent', name: '@benz-ai-x/dsh-24pa/agent' };

function jsExpr(expr) {
  const scalar = new Scalar(expr);
  scalar.tag = JS_EXPR_TAG.tag;
  return scalar;
}

// New rows serialize their package names single-quoted, matching the style
// the baseline file itself uses for `name: '@deepseek-ai/...'` scalars.
function createRow(doc, spec) {
  const row = doc.createNode(spec);
  const name = row.get('name', true);
  if (name) name.type = 'QUOTE_SINGLE';
  return row;
}

function fail(message) {
  throw new Error(`[sync-preset] ${message}`);
}

function anchorMissing(what, id) {
  return fail(`anchor missing: ${what} (id "${id}") — the baseline preset changed; re-derive the delta rule before regenerating`);
}

function rowById(seq, id, what) {
  const row = seq.items.find((item) => item.get('id') === id);
  if (!row) anchorMissing(what, id);
  return row;
}

function removeRow(seq, id, what) {
  const row = rowById(seq, id, what);
  seq.items.splice(seq.items.indexOf(row), 1);
}

// tool-schedule is excluded from the pa24 preset, so the deny lists the
// standard preset carries for its sake must go too — but only if they deny
// nothing else. Anything beyond the four schedule tools means upstream
// repurposed the filter and a human must review.
function dropScheduleToolFilter(configNode, rowId) {
  const toolFilter = configNode.get('toolFilter', true);
  if (!toolFilter) return;
  const denied = toolFilter.get('deny', true)?.items?.map((item) => item.value) ?? [];
  const extra = denied.filter((name) => !SCHEDULE_TOOLS.includes(name));
  if (extra.length) fail(`toolFilter of "${rowId}" denies non-schedule tools ${JSON.stringify(extra)} — review the delta before regenerating`);
  configNode.delete('toolFilter');
}

function headerComment(baselineVersion) {
  return [
    `GENERATED by packages/24pa/scripts/sync-preset.mjs from the`,
    `@deepseek-ai/dsh-web-app standard preset (baseline ${baselineVersion}; verified`,
    `compatible with dsh hosts up to 0.2.1-rc.3 — the alpha.2-era drift is now`,
    `absorbed into the baseline: subagent schedule denies are removed (aligned`,
    `with our tool-schedule omission below), plan-mode prompt wording updated,`,
    `and a disabled tool-plugin-market row stays out like plugin-manager).`,
    `Do not edit by hand: run "npm run preset:sync" and commit the diff;`,
    `"npm run preset:check" guards the checked-in copy against drift.`,
    ``,
    `24私助（24PA）formal bundle: one assistant preset plus the host plugin row.`,
    `The preset carries the full standard-mode capability base (persona merged into`,
    `the assistant identity), enables ralph / subagent_codex / subagent_claude_code,`,
    `and omits tool-schedule by design: reminders stay on the ledger, so the`,
    `schedule toolFilter denies and modelSelectionSettings drop with it.`,
    `tool-plugin-manager stays out (profile plugin management is not a pa24`,
    `capability). subagent_codex / subagent_claude_code mount only after their`,
    `provider bundles (@deepseek-ai/dsh-subagent-codex / -claude-code) are installed`,
    `into the profile; the ralph / subagent_codex / subagent_claude_code rows stay`,
    `enabled by design even where the baseline's own catalog moved them to`,
    `experimental — the packages ship with the installation and keep resolving.`,
    `The host plugin row below is pa24-owned and never derives`,
    `from the standard preset.`,
  ].map((line) => (line ? `# ${line}` : '#')).join('\n');
}

/** Apply the pa24 delta to the parsed standard-preset document, in place. */
function applyPa24Delta(doc) {
  const entries = doc.contents;
  if (entries?.items === undefined) fail('baseline file must be a top-level YAML sequence of patch entries');

  let presetRow;
  let presetInsert;
  for (const entry of entries.items) {
    const insert = entry.get('insert', true);
    if (!insert) continue;
    const match = insert.items.find((item) => item.get('id') === 'preset-standard');
    if (match) {
      if (presetRow) fail('multiple preset-standard rows in the baseline file');
      presetRow = match;
      presetInsert = insert;
    }
  }
  if (!presetRow) fail('anchor missing: the standard agent-preset row (id "preset-standard")');
  if (presetRow.get('name') !== '@deepseek-ai/dsh-agent-preset') {
    fail(`preset-standard row is no longer @deepseek-ai/dsh-agent-preset (got ${presetRow.get('name')})`);
  }

  // Preset identity: id/name/description in that order, `order` dropped.
  presetRow.set('id', PRESET.rowId);
  const config = presetRow.get('config', true);
  if (config.get('id') !== 'standard') fail('preset config.id is not "standard"');
  const plugins = config.get('plugins', true);
  if (!Array.isArray(plugins?.items)) fail('preset config.plugins is not a list');
  config.delete('order');
  config.delete('plugins');
  config.set('id', PRESET.configId);
  config.set('name', PRESET.name);
  config.set('description', PRESET.description);
  config.set('plugins', plugins);

  // Persona: the 24私助 identity replaces the coding-agent default.
  const persona = rowById(plugins, 'persona', 'persona plugin');
  if (persona.get('name') !== '@deepseek-ai/dsh-persona') fail('persona row is no longer @deepseek-ai/dsh-persona');
  const prefix = persona.getIn(['config', 'prefix'], true);
  if (prefix?.value === undefined) fail('persona config.prefix missing');
  prefix.value = PRESET.personaPrefix;

  // Reminders stay on the ledger: the schedule tool and everything the
  // standard preset carries for its sake are excluded. The cleanup covers the
  // rows that carry schedule-related keys on this baseline (the delegation
  // subagents) plus the plan-mode row, where earlier baselines carried the
  // same deny list; a row that denies anything beyond the schedule tools
  // fails loud instead of being silently rewritten.
  removeRow(plugins, 'tool-schedule', 'the schedule tool row');
  const delegation = rowById(plugins, 'delegation', 'delegation group');
  if (!delegation.get('group')) fail('delegation row is not a group');
  const delegationRows = delegation.get('config', true);
  if (!Array.isArray(delegationRows?.items)) fail('delegation group config is not a list');
  let fork;
  for (const rowId of ['tool-subagent', 'tool-subagent-fork']) {
    const row = rowById(delegationRows, rowId, `delegation row ${rowId}`);
    const rowConfig = row.get('config', true);
    if (!rowConfig) fail(`${rowId} has no config`);
    rowConfig.delete('modelSelectionSettings');
    dropScheduleToolFilter(rowConfig, rowId);
    if (rowId === 'tool-subagent-fork') fork = row;
  }
  const planning = rowById(plugins, 'planning', 'planning group');
  dropScheduleToolFilter(rowById(planning.get('config', true), 'plan-mode', 'plan-mode row').get('config', true), 'plan-mode');

  // External CLI delegation and ralph ride inside the delegation group,
  // after the rows the standard preset already ships there.
  delegationRows.items.splice(delegationRows.items.indexOf(fork) + 1, 0, ...EXTERNAL_SUBAGENTS.map((row) => createRow(doc, row)));
  const workflow = rowById(delegationRows, 'tool-workflow', 'delegation row tool-workflow');
  delegationRows.items.splice(delegationRows.items.indexOf(workflow) + 1, 0, createRow(doc, RALPH_ROW));

  // The business tool surface; plugin management is not a pa24 capability.
  removeRow(plugins, 'tool-plugin-manager', 'the plugin-manager tool row');
  plugins.items.push(createRow(doc, PA24_AGENT_ROW));

  // Host plugin row: pa24-owned, static. It rides INSIDE the same insert list
  // as the preset row — a bare top-level patch entry would be an id-targeted
  // override with no matching row in the base composition and get skipped.
  const hostConfig = new YAMLMap();
  hostConfig.add({ key: 'stateDirectory', value: jsExpr("dshHomePath('24pa')") });
  hostConfig.add({ key: 'backupSessionsRoot', value: jsExpr("dshHomePath('sessions')") });
  hostConfig.add({ key: 'backupStoragesRoot', value: jsExpr("dshHomePath('storages')") });
  hostConfig.add({ key: 'backupAttachmentsRoot', value: jsExpr("dshHomePath('attachments', 'v1')") });
  hostConfig.add({ key: 'workspacePath', value: jsExpr("process.env.PA24_WORKSPACE || ''") });
  hostConfig.add({ key: 'larkCliBin', value: 'lark-cli' });
  hostConfig.add({ key: 'wecomCliBin', value: 'wecom-cli' });
  const hostRow = createRow(doc, { id: 'pa24', name: '@benz-ai-x/dsh-24pa' });
  hostRow.set('config', hostConfig);
  presetInsert.items.push(hostRow);

  // F40（spec 2.11）：registry（dsh-skill）由 web 应用组合提供，不再加行（重复
  // 注册会炸整组激活）。skill-filesystem/tool-skill 基线行在 agent 预设层，本
  // 插件的全局层读不到其 provider——这里补两行进 profile 层，工作区 .dsh/skills
  // 的自定义 skill 才对计划绑定目录可见；宿主未提供 registry 时插件回落内置三件。
  for (const id of ['pa24-skill-filesystem', 'pa24-skill-tool']) {
    presetInsert.items.push(createRow(doc, SKILL_STACK_ROWS[id]));
  }
}

/** F40：skill 体系补充行的固定定义（registry 不加——web 应用已注册该服务）。 */
const SKILL_STACK_ROWS = {
  'pa24-skill-filesystem': { id: 'pa24-skill-filesystem', name: '@deepseek-ai/dsh-skill-filesystem' },
  'pa24-skill-tool': { id: 'pa24-skill-tool', name: '@deepseek-ai/dsh-tool-skill' },
};

/** Generate the pa24 cordis.patch.yml text from the standard preset text. */
export function generatePa24Patch(standardText, baselineVersion) {
  const doc = parseDocument(standardText, { customTags: [JS_EXPR_TAG] });
  if (doc.errors.length) fail(`baseline file does not parse: ${doc.errors[0]}`);
  applyPa24Delta(doc);
  // Drop the baseline's own header comment: it describes the standard preset,
  // and this file's header is the generator's provenance note below.
  doc.commentBefore = null;
  doc.comment = null;
  for (const entry of doc.contents.items) entry.commentBefore = null;
  const body = String(doc).replace(/\n*$/, '\n');
  return `${headerComment(baselineVersion)}\n${body}`;
}

/** Resolve the installed baseline's standard.patch.yml and its version. */
export function resolveBaseline() {
  const webAppPackageJson = require.resolve('@deepseek-ai/dsh-web-app/package.json');
  const version = JSON.parse(readFileSync(webAppPackageJson, 'utf8')).version;
  const standardPath = resolve(dirname(webAppPackageJson), 'presets/standard.patch.yml');
  return { standardPath, version };
}

function firstDiffLines(before, after, limit = 12) {
  const a = before.split('\n');
  const b = after.split('\n');
  const lines = [];
  for (let i = 0; i < Math.max(a.length, b.length) && lines.length < limit; i++) {
    if (a[i] !== b[i]) lines.push(`  L${i + 1}  - ${a[i] ?? '<eof>'}\n  L${i + 1}  + ${b[i] ?? '<eof>'}`);
  }
  return lines.join('\n');
}

function main() {
  const check = process.argv.slice(2).includes('--check');
  const { standardPath, version } = resolveBaseline();

  const generated = generatePa24Patch(readFileSync(standardPath, 'utf8'), version);
  const target = resolve(pkgDir, 'cordis.patch.yml');
  const current = readFileSync(target, 'utf8');

  if (generated === current) {
    console.log(`[sync-preset] cordis.patch.yml 已与基线 ${version} 同步`);
    return;
  }
  if (!check) {
    writeFileSync(target, generated, 'utf8');
    console.log(`[sync-preset] 已按基线 ${version} 重新生成 cordis.patch.yml`);
    return;
  }
  console.error(`[sync-preset] cordis.patch.yml 与基线 ${version} 的生成结果不一致（差异预览）：`);
  console.error(firstDiffLines(current, generated));
  console.error('[sync-preset] 运行 "npm run preset:sync" 重新生成并提交，或修正 scripts/sync-preset.mjs 的 delta 规则。');
  process.exitCode = 1;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
