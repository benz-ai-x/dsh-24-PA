import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { bootHost } from '../tests/helpers/host.mjs';
import { startMockLlm } from '../tests/helpers/mock-llm.mjs';
import { DEFAULT_CONFIG } from '../lib/config.js';
const root = await mkdtemp(join(tmpdir(), 'manticore-m02-work-ui-')), workspace = join(root, 'workspace');
await mkdir(workspace);
await writeFile(join(workspace, 'AGENTS.md'), '# M02 交办界面隔离示例\n\n```json\n' + JSON.stringify({ ...DEFAULT_CONFIG, storage: 'sqlite', maxWorkers: 3 }, null, 2) + '\n```\n');
const scriptPath = join(root, 'script.json');
const script = async (title, waiting = false) => writeFile(scriptPath, JSON.stringify({ mode: 'dispatch', delegate: { worker: 'memo', title, instruction: '核对隔离示例并形成报告；不读取或写入真实账号。', completionCriteria: '结果含原输入依据和未完成项', acceptanceRequired: true }, workerTool: { name: 'pa24_run', input: waiting ? { action: 'wait', kind: 'input', reason: '等待主人补充报告主题，沿原交办继续。' } : { action: 'progress', stage: '核对完成', completed: '已核对原输入与示例资料', next: '提交报告并等待主人验收' } }, workerReply: '隔离示例报告：已完成原输入核对；依据为本次请求，无真实外部动作。未完成项：无。' }));
await script('M02 隔离示例');
const llm = await startMockLlm({ scriptPath, logPath: join(root, 'requests.json'), recordInputs: true });
const host = await bootHost({ env: { PA24_WORKSPACE: workspace, PA24_TRANSPORT: 'fake', DEEPSEEK_API_KEY: 'test-key', DEEPSEEK_BASE_URL: llm.url } });
const ready = await host.waitUntil(row => Boolean(row.workspaceBinding && row.workspace?.localSessionId));
const create = async (title, waiting) => {
  await script(title, waiting);
  await host.remote('session/prompt', { request: { requestId: randomUUID(), sessionId: ready.workspace.localSessionId, mode: 'queue', content: [{ type: 'text', text: title + '，仅执行隔离示例。' }] } });
  const state = await host.waitUntil(row => row.work.some(work => work.title === title && work.status === (waiting ? 'waiting_input' : 'completed')), { timeoutMs: 30000 });
  return state.work.find(work => work.title === title).id;
};
const completed = await create('M02 示例：完整报告待验收', false);
const waiting = await create('M02 示例：等待主人补充主题', true);
await script('M02 示例：按主人输入接续');
await writeFile('/tmp/manticore-m02-work-ui-state.json', JSON.stringify({ root, workspace, scriptPath, hostRoot: host.root, url: host.url, binding: ready.workspaceBinding, completed, waiting }));
console.log(JSON.stringify({ url: host.url, root, completed, waiting }));
const stop = async () => { await host.stop(); await llm.close(); await rm(root, { recursive: true, force: true }); process.exit(); };
process.on('SIGTERM', stop); process.on('SIGINT', stop);
