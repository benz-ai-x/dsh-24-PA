import { SqliteDb } from '/Users/pc2026/.codex/worktrees/main-final-architecture/dsh-24-PA/packages/24pa/lib/sqlite.js';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = await mkdtemp(join(tmpdir(), 'pa24-v05-spec-close-'));
const db = new SqliteDb(join(root, 'ledger.db'));
await db.migrate();
const entered = Promise.withResolvers(), release = Promise.withResolvers(), rescue = Promise.withResolvers();
const state = { transaction: 'pending', backup: 'pending', outsideClose: 'pending', insideClose: 'not-called' };
const transaction = db.withTransaction(async tx => {
  await tx.query("insert into pa24.memo(id, topic, content, source) values ('marker', 'backup', 'keep', 'spec-review')");
  entered.resolve();
  await release.promise;
  state.insideClose = 'pending';
  const insideClose = db.close();
  insideClose.then(() => state.insideClose = 'resolved', () => state.insideClose = 'rejected');
  await Promise.race([insideClose, rescue.promise]);
});
transaction.then(() => state.transaction = 'resolved', () => state.transaction = 'rejected');
await entered.promise;
const backup = db.backup();
backup.then(() => state.backup = 'resolved', () => state.backup = 'rejected');
const outsideClose = db.close();
outsideClose.then(() => state.outsideClose = 'resolved', () => state.outsideClose = 'rejected');
release.resolve();
await new Promise(resolve => setTimeout(resolve, 100));
console.log(JSON.stringify({ node: process.version, after100ms: { ...state }, explanation: 'inside close waits for outside close, which is queued behind this transaction and its accepted backup' }));
rescue.resolve();
await Promise.all([transaction, backup, outsideClose]);
await rm(root, { recursive: true, force: true });
console.log(JSON.stringify({ rescuedForCleanup: state }));
